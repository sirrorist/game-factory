// Пререлиз - версия до 1.0.0 (0.x.y) или с суффиксом semver (1.0.0-beta.1): игра ещё в работе.
// Хаб показывает её только владельцу (D-060). Сервер игр по прямой ссылке её отдаёт, и код
// лежит в публичном репозитории - это скрытие из витрины, а не защита доступа.

const VERSION = /^(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z.-]+)?$/;

export function isPrerelease(version: string): boolean {
  const m = VERSION.exec(version);
  // Непонятная версия - не показываем гостю: витрина не должна угадывать.
  if (!m) return true;
  return m[1] === '0' || m[4] !== undefined;
}
